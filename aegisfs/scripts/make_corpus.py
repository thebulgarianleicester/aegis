#!/usr/bin/env python3
"""Generate ONLY new synthetic paired data. Never accepts a source file or directory.

AES-256-CTR and ChaCha20 are used solely to transform in-memory generated bytes;
no existing files are read or modified. Deterministic keys are public test vectors,
not suitable for protecting data. OpenSSL is required on PATH.
"""
import argparse
import csv
import gzip
import hashlib
import json
import random
import subprocess
import sys
from pathlib import Path

SIZE = 65536
BLOCK = 4096


def transform(data: bytes, algorithm: str, sample: int) -> bytes:
    if algorithm not in ("aes-256-ctr", "chacha20"):
        raise ValueError("unsupported algorithm")
    material = hashlib.sha512(f"aegisfs-research-{algorithm}-{sample}".encode()).digest()
    command = ["openssl", "enc", f"-{algorithm}", "-K", material[:32].hex(),
               "-iv", material[32:48].hex(), "-nopad"]
    result = subprocess.run(command, input=data, stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, check=True)
    if len(result.stdout) != len(data):
        raise ValueError("unexpected ciphertext length")
    return result.stdout


def text_for(sample: int) -> bytes:
    header = b"%PDF-1.7\n% synthetic test bytes, not a valid PDF\n"
    lines = [f"Synthetic invoice {sample:04d}-{i:05d} category {i % 11}: total {i * 13 % 9000:04d}.\n".encode()
             for i in range(1500)]
    return (header + b"".join(lines))[:SIZE].ljust(SIZE, b" ")


def archive_for(rng: random.Random) -> bytes:
    # A gzip member of incompressible synthetic content; not a corpus of real files.
    return gzip.compress(rng.randbytes(SIZE), compresslevel=9, mtime=0)


def write_exclusive(path: Path, data: bytes) -> None:
    with path.open("xb") as stream:
        stream.write(data)


def generate(out: Path, samples: int, seed: int) -> dict:
    # Fail if the target already exists. All outputs are newly created beneath it.
    out.mkdir(exist_ok=False)
    rng = random.Random(seed)
    rows = []
    for i in range(samples):
        text = text_for(i)
        edited = bytearray(text)
        edited[128:140] = b"UPDATED-2026"
        aes = transform(text, "aes-256-ctr", i)
        chacha = transform(text, "chacha20", i)
        intermittent = bytearray(text)
        selected = list(range(0, SIZE // BLOCK, 4))
        for block in selected:
            start = block * BLOCK
            intermittent[start:start + BLOCK] = aes[start:start + BLOCK]
        gz_a, gz_b = archive_for(rng), archive_for(rng)
        max_gz_len = max(len(gz_a), len(gz_b))
        gz_a, gz_b = gz_a.ljust(max_gz_len, b"\0"), gz_b.ljust(max_gz_len, b"\0")
        # A challenging benign rewrite: high entropy replaces low entropy.
        random_rewrite = rng.randbytes(SIZE)
        # Encryption of already-high-entropy data is a hard delta-H test case.
        encrypted_gz = transform(gz_a, "aes-256-ctr", 100000 + i)
        cases = [
            ("benign_text_edit", text, bytes(edited), "benign", ""),
            ("benign_gzip_replacement", gz_a, gz_b, "benign", ""),
            ("benign_random_rewrite", text, random_rewrite, "benign", ""),
            ("aes_full_text", text, aes, "suspicious", ""),
            ("chacha_full_text", text, chacha, "suspicious", ""),
            ("aes_intermittent_text", text, bytes(intermittent), "suspicious", ";".join(map(str, selected))),
            ("aes_full_gzip", gz_a, encrypted_gz, "suspicious", ""),
        ]
        for workload, pre, post, label, blocks in cases:
            if len(pre) != len(post) or not pre:
                raise AssertionError("invalid paired synthetic data")
            stem = f"{workload}_{i:04d}"
            pre_name, post_name = stem + ".pre", stem + ".post"
            write_exclusive(out / pre_name, pre)
            write_exclusive(out / post_name, post)
            rows.append((pre_name, post_name, label, blocks, workload))
    with (out / "manifest.csv").open("x", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(["pre", "post", "label", "positive_blocks", "workload"])
        writer.writerows(rows)
    info = {"schema": 1, "seed": seed, "samples_per_workload": samples, "pairs": len(rows),
            "block_bytes": BLOCK, "synthetic_only": True,
            "notes": "Public deterministic keys; synthetic byte streams; not representative real-world data.",
            "python": sys.version, "openssl": subprocess.check_output(["openssl", "version"], text=True).strip()}
    with (out / "metadata.json").open("x") as stream:
        json.dump(info, stream, indent=2)
        stream.write("\n")
    return info


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path, help="new directory; must not already exist")
    parser.add_argument("--samples", type=int, default=10, help="samples per workload (1–200)")
    parser.add_argument("--seed", type=int, default=2026)
    args = parser.parse_args()
    if not 1 <= args.samples <= 200:
        parser.error("samples must be in 1..200")
    info = generate(args.output, args.samples, args.seed)
    print(f"Created {info['pairs']} synthetic file pairs in {args.output}")


if __name__ == "__main__":
    main()
